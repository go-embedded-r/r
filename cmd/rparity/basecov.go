func readTSV(path string) ([][]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var rows [][]string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		rows = append(rows, strings.Split(sc.Text(), "\t"))
	}
	return rows, sc.Err()
}

// usedNames is the set of function names called in the golden snippets.
func usedNames(root string) (map[string]bool, error) {
	snippets, err := gen.EvalInputs(root)
	if err != nil {
		return nil, err
	}
	used := map[string]bool{}
	var walk func(syntax.Node)
	walk = func(n syntax.Node) {
		switch x := n.(type) {
		case *syntax.Call:
			if s, ok := x.Fun.(*syntax.Sym); ok {
				used[s.Name] = true
			} else {
				walk(x.Fun)
			}
			for _, a := range x.Args {
				walk(a.Value)
			}
		case *syntax.Function:
			for _, p := range x.Params {
				walk(p.Default)
			}
			walk(x.Body)
		}
	}
	for _, src := range snippets {
		f, err := syntax.ParseAll(src)
		if err != nil {
			continue
		}
		for _, e := range f.Exprs {
			walk(e)
		}
	}
	return used, nil
}

// basecovCmd measures how much of base R's exported functions the evaluator
// has, from the data under testdata/base (generated by the oracle).
func basecovCmd() *cobra.Command {
	var order int
	cmd := &cobra.Command{
		Use:   "basecov",
		Short: "coverage of base R's exported functions, and the order that unlocks the most closures",
		Args:  cobra.NoArgs,
		RunE: func(c *cobra.Command, _ []string) error {
			exports, err := readTSV("testdata/base/exports.tsv")
			if err != nil {
				return err
			}
			needs, err := readTSV("testdata/base/needs.tsv")
			if err != nil {
				return err
			}
			used, err := usedNames(".")
			if err != nil {
				return err
			}
			have := map[string]bool{}
			for _, n := range eval.Builtins() {
				have[n] = true
			}
			for _, n := range eval.Unsupported() {
				delete(have, n)
			}
			out := c.OutOrStdout()
			var nPrim, nClo, havePrim, haveClo, agreePrim, agreeClo int
			for _, r := range exports {
				if len(r) < 2 {
					continue
				}
				name, kind := r[0], r[1]
				if kind == "primitive" {
					nPrim++
					if have[name] {
						havePrim++
						if used[name] {
							agreePrim++
						}
					}
				} else {
					nClo++
					if have[name] {
						haveClo++
						if used[name] {
							agreeClo++
						}
					}
				}
			}
			total := nPrim + nClo
			fmt.Fprintf(out, "base exports: %d (%d primitives, %d closures)\n", total, nPrim, nClo)
			fmt.Fprintf(out, "implemented: %d primitives, %d closures\n", havePrim, haveClo)
			fmt.Fprintf(out, "agreeing with the oracle (implemented and exercised by a passing golden): %d primitives, %d closures = %d of %d (%.1f%%)\n",
				agreePrim, agreeClo, agreePrim+agreeClo, total, 100*float64(agreePrim+agreeClo)/float64(total))

			// closures by the internals they call
			need := map[string][]string{}
			for _, r := range needs {
				if len(r) == 2 {
					need[r[0]] = strings.Split(r[1], ",")
				}
			}
			pure := 0
			remaining := map[string]map[string]bool{}
			for _, r := range exports {
				if len(r) < 2 || r[1] != "closure" || have[r[0]] {
					continue
				}
				ns := need[r[0]]
				if len(ns) == 0 {
					pure++
					continue
				}
				set := map[string]bool{}
				for _, k := range ns {
					if !have[k] {
						set[k] = true
					}
				}
				if len(set) == 0 {
					pure++
					continue
				}
				remaining[r[0]] = set
			}
			fmt.Fprintf(out, "closures not implemented that call no missing .Internal (a rewrite in R or Go suffices): %d\n", pure)
			fmt.Fprintf(out, "closures blocked by at least one missing .Internal: %d\n\n", len(remaining))
			fmt.Fprintf(out, "next .Internal functions, each chosen to unlock the most closures after the ones before it\n\n| # | internal | unlocks | total |\n|---|---|---|---|\n")
			cum := 0
			for i := 1; i <= order; i++ {
				score := map[string]int{}
				for _, set := range remaining {
					if len(set) == 1 {
						for k := range set {
							score[k]++
						}
					}
				}
				if len(score) == 0 {
					// no closure is one step away: take the internal in most remaining sets
					for _, set := range remaining {
						for k := range set {
							score[k]++
						}
					}
				}
				if len(score) == 0 {
					break
				}
				var keys []string
				for k := range score {
					keys = append(keys, k)
				}
				sort.Slice(keys, func(a, b int) bool {
					if score[keys[a]] != score[keys[b]] {
						return score[keys[a]] > score[keys[b]]
					}
					return keys[a] < keys[b]
				})
				pick := keys[0]
				unlocked := 0
				for fn, set := range remaining {
					delete(set, pick)
					if len(set) == 0 {
						unlocked++
						delete(remaining, fn)
					}
				}
				cum += unlocked
				fmt.Fprintf(out, "| %d | `%s` | %d | %d |\n", i, pick, unlocked, cum)
			}
			return nil
		},
	}
	cmd.Flags().IntVar(&order, "order", 40, "how many internals to list")
	return cmd
}
